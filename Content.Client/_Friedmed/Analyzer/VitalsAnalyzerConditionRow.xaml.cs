using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Friedmed.Analyzer;

[GenerateTypedNameReferences]
public sealed partial class VitalsAnalyzerConditionRow : BoxContainer
{
    public VitalsAnalyzerConditionRow()
    {
        RobustXamlLoader.Load(this);
    }

    public void Update(VitalsAnalyzerCondition condition)
    {
        ConditionName.Text = condition.Text;
        ConditionName.FontColorOverride = condition.Color;

        ToolTip = condition.ToolTip;

        ConditionIcon.Texture = condition.Icon;
        ConditionIcon.Visible = condition.Icon != null;
    }
}
