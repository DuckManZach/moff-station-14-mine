using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Friedmed.Analyzer;

public readonly record struct VitalsAnalyzerCondition(string Text, string? ToolTip, Color Color, Texture? Icon = null);

[GenerateTypedNameReferences]
public sealed partial class VitalsAnalyzerBodyPartRow : PanelContainer
{
    private static readonly StyleBoxFlat AlternateStyle = new(Color.White.WithAlpha(0.04f));

    private readonly StyleBoxFlat _barStyle = new();

    public VitalsAnalyzerBodyPartRow()
    {
        RobustXamlLoader.Load(this);

        HealthBar.ForegroundStyleBoxOverride = _barStyle;
        HealthBar.BackgroundStyleBoxOverride = new StyleBoxFlat(Color.Transparent);
    }

    public void Update(string name, float? health, Color color, List<VitalsAnalyzerCondition> conditions, bool alternate)
    {
        PanelOverride = alternate ? AlternateStyle : null;

        PartName.Text = name;
        PartName.FontColorOverride = color;

        HealthBar.Visible = health != null;
        HealthBar.Value = health ?? 0f;
        _barStyle.BackgroundColor = color;

        SyncChildren(Conditions, conditions.Count, () => new VitalsAnalyzerConditionRow());
        for (var i = 0; i < conditions.Count; i++)
        {
            ((VitalsAnalyzerConditionRow) Conditions.GetChild(i)).Update(conditions[i]);
        }
    }

    /// Rows get reused between scans, so an open tooltip or the scroll position survives the once-a-second update.
    public static void SyncChildren(Control container, int count, Func<Control> factory)
    {
        while (container.ChildCount > count)
        {
            container.RemoveChild(container.ChildCount - 1);
        }

        while (container.ChildCount < count)
        {
            container.AddChild(factory());
        }
    }
}
