using Robust.Shared.Prototypes;
using Robust.Shared.Utility;

namespace Content.Client._Friedmed.Analyzer;

[GenerateTypedNameReferences]
public sealed partial class VitalsAnalyzerControl : BoxContainer
{
    [Dependency] private IEntityManager _entity = default!;
    [Dependency] private IPrototypeManager _prototype = default!;

    private readonly ProgressColorSystem _progressColor;
    private readonly SpriteSystem _sprite;

    /// Off where there's no room for it, like the examine tooltip.
    public bool ShowBodyParts
    {
        get => BodyPartsPanel.Visible;
        set => BodyPartsPanel.Visible = value;
    }

    public VitalsAnalyzerControl()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        _progressColor = _entity.System<ProgressColorSystem>();
        _sprite = _entity.System<SpriteSystem>();
    }

    public void Update((VitalsData, EntityUid, bool)? scan)
    {
        if (scan is not var (data, target, updating))
        {
            NoPatientPlaceholder.Visible = true;
            MainContent.Visible = false;
            return;
        }

        NoPatientPlaceholder.Visible = false;
        MainContent.Visible = true;

        PatientView.SetEntity(target);
        PatientView.Visible = updating;
        OutOfRange.Visible = !updating;

        MainContent.Modulate =
            updating
                ? Color.White
                : Color.White.WithAlpha(0.4f);

        NameLabel.Text = Identity.Name(target, _entity);
        SpeciesLabel.Text =
            _entity.TryGetComponent<HumanoidProfileComponent>(target,
                out var humanoidComponent)
                ? Loc.GetString(_prototype.Index(humanoidComponent.Species).Name)
                : Loc.GetString("health-analyzer-window-entity-unknown-species-text");

        var pain = data.PainStatus is { } painStatus
            ? Capitalized(_prototype.Index(painStatus).Name)
            : Loc.GetString("offbrand-vitals-pain-none");
        SetCondition(PainValue, pain, 1f - data.Pain);

        SetCondition(BrainActivityValue, Loc.GetString("offbrand-vitals-brain-activity-value", ("value", $"{data.BrainHealth * 100:F0}")), data.BrainHealth);

        SpO2Label.Text = Loc.GetString(data.Spo2Name);
        SetCondition(SpO2Value, Loc.GetString("offbrand-vitals-spo2-value", ("value", $"{data.Spo2 * 100:F0}")), data.Spo2);

        RespiratoryRateValue.Text = Loc.GetString("offbrand-vitals-respiratory-rate-value", ("value", data.RespiratoryRate));

        EtCO2Label.Text = Loc.GetString(data.Etco2Name);
        EtCO2Value.Text = Loc.GetString("offbrand-vitals-etco2-value", ("value", data.Etco2));

        var (systolic, diastolic) = data.BloodPressure;
        BloodPressureValue.Text = Loc.GetString("offbrand-vitals-blood-pressure-value", ("systolic", systolic), ("diastolic", diastolic));
        SetCondition(BloodVolumeValue, Loc.GetString("offbrand-vitals-blood-volume-value", ("value", $"{data.BloodLevel * 100:F0}")), data.BloodLevel);

        SetCondition(HeartRateValue, Loc.GetString("offbrand-vitals-heart-rate-value", ("value", data.HeartRate)), 1f - data.HeartStrain);

        if (ShowBodyParts)
            UpdateBodyParts(data, target);
    }

    private void SetCondition(Label label, string text, float health)
    {
        label.Text = text;
        label.FontColorOverride = _progressColor.GetProgressColor(Math.Clamp(health, 0f, 1f));
    }

    private void UpdateBodyParts(VitalsData data, EntityUid target)
    {
        var wholeBody = WholeBodyConditions(data);
        var bleedAlert = _entity.TryGetComponent<BloodstreamComponent>(target, out var bloodstream)
            ? _prototype.Index(bloodstream.BleedingAlert)
            : null;
        var parts = data.BodyParts ?? [];
        var offset = wholeBody.Count != 0 ? 1 : 0;

        VitalsAnalyzerBodyPartRow.SyncChildren(BodyPartRows, parts.Count + offset, () => new VitalsAnalyzerBodyPartRow());
        NoInjuries.Visible = BodyPartRows.ChildCount == 0;

        if (offset != 0)
        {
            var row = (VitalsAnalyzerBodyPartRow) BodyPartRows.GetChild(0);
            row.Update(Loc.GetString("offbrand-vitals-whole-body"), null, Color.White, wholeBody, false);
        }

        for (var i = 0; i < parts.Count; i++)
        {
            var part = parts[i];
            var row = (VitalsAnalyzerBodyPartRow) BodyPartRows.GetChild(i + offset);
            var color = part.Missing ? Color.Gray : _progressColor.GetProgressColor(part.Health);

            row.Update(Capitalized(_prototype.Index(part.Organ).Name), part.Health, color, PartConditions(part, bleedAlert), (i + offset) % 2 != 0);
        }
    }

    private List<VitalsAnalyzerCondition> WholeBodyConditions(VitalsData data)
    {
        var conditions = new List<VitalsAnalyzerCondition>();

        var reagents = (data.Reagents ?? [])
            .Select(reagent => (Name: _prototype.Index(reagent.Key).LocalizedName, Amounts: reagent.Value))
            .OrderBy(reagent => reagent.Name);

        foreach (var (name, (inBloodstream, metabolites)) in reagents)
        {
            conditions.Add(new(
                Loc.GetString("offbrand-vitals-reagent", ("reagent", name), ("amount", inBloodstream + metabolites)),
                Loc.GetString("offbrand-vitals-reagent-tooltip", ("bloodstream", inBloodstream), ("metabolites", metabolites)),
                Color.LightSkyBlue));
        }

        if (data.NonMedicalReagents)
        {
            conditions.Add(new(
                Loc.GetString("offbrand-vitals-non-medical-reagents"),
                FormattedMessage.RemoveMarkupPermissive(Loc.GetString("health-analyzer-window-entity-non-medical-reagents")),
                Color.Yellow));
        }

        return conditions;
    }

    private List<VitalsAnalyzerCondition> PartConditions(BodyPartData part, AlertPrototype? bleedAlert)
    {
        var conditions = new List<VitalsAnalyzerCondition>();

        if (part.Missing)
        {
            conditions.Add(new(Loc.GetString("offbrand-vitals-part-missing"), null, Color.Gray));
            return conditions;
        }

        foreach (var condition in part.Conditions)
        {
            var text = Loc.GetString("offbrand-vitals-condition", ("name", _prototype.Index(condition.Wound).Name), ("count", condition.Count));

            if (condition.Tended)
                text = Loc.GetString("offbrand-vitals-condition-tended", ("condition", text));

            var bleeding = condition.BleedLevel > 0f;
            var icon = bleeding && bleedAlert != null
                ? _sprite.Frame0(bleedAlert.GetIcon(Math.Clamp((short) condition.BleedLevel, bleedAlert.MinSeverity, bleedAlert.MaxSeverity)))
                : null;

            var color = bleeding ? Color.Red : condition.Tended ? Color.Gray : Color.White;
            conditions.Add(new(text, ConditionToolTip(condition), color, icon));
        }

        // Damaged organs have no wound to list, but shouldn't show up as an empty row.
        if (conditions.Count == 0)
            conditions.Add(new(Loc.GetString("offbrand-vitals-part-damaged"), null, Color.White));

        return conditions;
    }

    private static string? ConditionToolTip(BodyConditionData condition)
    {
        var description = condition.Description is { } descriptionId
            ? FormattedMessage.RemoveMarkupPermissive(Loc.GetString(descriptionId, ("count", condition.Count)))
            : null;

        if (condition.Damage <= 0)
            return description;

        var damage = Loc.GetString("offbrand-vitals-condition-damage", ("damage", condition.Damage));
        return description == null ? damage : $"{description}\n{damage}";
    }

    private static string Capitalized(string name)
    {
        return Loc.GetString("offbrand-vitals-capitalized", ("name", name));
    }
}
